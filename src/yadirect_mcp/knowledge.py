def index() -> str:
    """Оглавление базы знаний с URI каждого документа."""
    lines = [
        "# База знаний по Яндекс Директу",
        "",
        (
            "Источники: официальная справка Яндекс Директа и документация API v5, "
            "материалы eLama, публичная практика агентств."
        ),
        "",
    ]
    lines += [f"- `direct://kb/{name}` — {summary}" for name, summary in DOCS.items()]
    return "\n".join(lines) + "\n"


def read(name: str) -> str:
    """Содержимое документа по имени из реестра.

    Имя сверяется с реестром, а не подставляется в путь: ресурсный URI приходит
    снаружи, и `../` в нём не должен выпускать чтение за каталог пакета.
    """
    if name not in DOCS:
        known = ", ".join(DOCS)
        raise ValueError(f"Нет документа {name!r}. Доступны: {known}")
    path = KB_DIR / f"{name}.md"
    if not path.is_file():
        raise FileNotFoundError(f"Файл базы знаний потерян при сборке пакета: {path}")
    return path.read_text(encoding="utf-8")
